/**
 * Convert amount from one currency to another using USD as pivot.
 * amount_in_to = amount_in_from * (rate[to] / rate[from])
 */
export function convertCurrency(
  amount: number,
  from: string,
  to: string,
  rates: RateTable = DEFAULT_EXCHANGE_RATES
): number {
  if (!Number.isFinite(amount)) return 0;
  if (from === to) return amount;
  const rf = rates[from] ?? rates[from.toUpperCase()];
  const rt = rates[to] ?? rates[to.toUpperCase()];
  if (!rf || !rt) return amount;
  return (amount / rf) * rt;
}

export function formatFx(
  amount: number,
  currencyCode: string,
  decimals = 2
): string {
  return `${currencyCode} ${amount.toLocaleString(undefined, {
    minimumFractionDigits: decimals,
    maximumFractionDigits: decimals,
  })}`;
}
